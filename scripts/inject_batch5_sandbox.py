# ============================================================================
# discrete-math/dm-ch03 · 十万顶点的图，邻接矩阵吃多少内存
# ----------------------------------------------------------------------------
# 教学点：两种存储的渐近阶不同——矩阵 O(n²)，邻接表 O(n+m)。
# 稀疏图上这个差别是灾难性的：
#   n=10 万、平均度 20 → m=100 万条边
#   矩阵  = 1e10 个 int32 = 38GB（直接 OOM）
#   邻接表 = (n + 2m) 个 8 字节节点 = 16MB
# 顺带把两条最短路算法的代价摆出来：Dijkstra 堆优化 O(m log n) 可跑，
# Floyd O(n³) 在这个规模下是 1e15 次操作，等于不可行。
# ============================================================================
