# ---------------------------------------------------------------------------
# 落盘
# ---------------------------------------------------------------------------
MODULES = {
    "discrete-math/dm-ch01": dm_ch01,
    "discrete-math/dm-ch02": dm_ch02,
    "discrete-math/dm-ch03": dm_ch03,
}


def main() -> int:
    """读取 labs.json → 写入 3 个 sandbox → 按仓库风格（indent=1/LF）落盘。"""
    with open(LABS, encoding="utf-8") as f:
        data = json.load(f)

    chapters = data.setdefault("chapters", {})
    for key, mod in MODULES.items():
        # 幂等：同一章节重复运行结果一致，不会叠加两份
        chapters[key] = [mod]
        print(f"added {key:<24} ({len(mod['params'])} params / {len(mod['checks'])} checks)")

    # indent=1 + newline="\n"：与仓库现有风格逐字节一致（indent=2 或 CRLF 会整份假 diff）
    with open(LABS, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print(f"written {os.path.normpath(LABS)}  (共 {len(chapters)} 章有精修模块)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
