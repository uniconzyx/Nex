"""批次五：给 discrete-math 三章补 sandbox（离散数学首次接入交互玩法）。

与 inject_batch3/4_sandbox.py 同一套路：把 sandbox 模块写进
content/_handmade/labs.json 的 chapters，再由 gen_interactive.py 并入
interactive.json 与前端数据。

为什么是这三章
-------------
沙盒的硬门槛是「参数能调、判据能算」。离散数学里真正的数量关系集中在
"计数爆炸"这条主线上，三章各有一个经典爆炸点：

  discrete-math/dm-ch01  命题逻辑：真值表 2^n 行 vs 2-CNF 蕴含图 2n 点 2m 边
  discrete-math/dm-ch02  集合与关系：幂集 2^n 个子集，指针列表 vs 位掩码
  discrete-math/dm-ch03  图论：邻接矩阵 n² vs 邻接表 n+m；Dijkstra vs Floyd

三章的共同教学点：**同一个问题，表示方式不同，代价差几个数量级**。
这正好是离散数学从"背定义"走向"能算账"的那一步。

四条纪律（沿用批次三/四，并补一条）
---------------------------------
1. checks 不能只写「目标态」，必须补取值下限（`nodes >= 10000`、
   `clauses >= 100`）。否则穷举求解读会退化成「所有旋钮拉到最小值」。
2. 既定事实用 `==` 锁死，且该值必须在参数网格上（`min + i*step`）。
   本批刻意**不用** `==` 锁"正确答案"（如 dm-ch02 的 mode）——让判据
   自己逼出正确选择，比直接锁死更有教学价值。
3. 默认值必须是「真实事故配置」：一打开就红，但红得有道理。
   dm-ch01 默认 8 变量（玩具规模，看不出问题）、dm-ch02 默认指针列表
   （24 元集 = 3072MB）、dm-ch03 默认 10 万顶点用矩阵（38GB）。
4. `if(c,a,b)` 在求值器里是**急切求值**（两分支都先算），除法要么保证
   除数恒非零，要么别放进 if 分支。本批 `if` 只用于选内存值，无除法。
5. fmt 只认 int / fix2 / pct。

写盘必须 indent=1 + newline="\\n"，与仓库现有风格逐字节一致。
"""
