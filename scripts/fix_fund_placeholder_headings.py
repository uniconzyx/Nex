def main() -> None:
    total = 0
    for cid, table in TITLES.items():
        base = f"content/fundamentals/{cid}/concept"
        for f in sorted(glob.glob(base + "/*.md")):
            stem = os.path.splitext(os.path.basename(f))[0]
            pair = table.get(stem)
            if not pair:
                continue
            s = open(f, encoding="utf-8").read()
            heads = [h for h in re.findall(r"^## (.+)$", s, re.M) if PLACEHOLDER.match(h.strip())]
            if len(heads) != 2:
                print(f"!! {cid}/{stem}: 占位标题 {len(heads)} 个，预期 2，跳过")
                continue
            bg, df = heads
            s2 = s.replace(f"## {bg}", f"## {pair[0]}", 1)
            s2 = s2.replace(f"## {df}", f"## {pair[1]}", 1)
            if s2 == s:
                print(f"== {cid}/{stem}: 无变化")
                continue
            with open(f, "w", encoding="utf-8", newline="") as fh:
                fh.write(s2)
            total += 1
            print(f"ok {cid}/{stem}")
    print(f"\n共改 {total} 个文件")


if __name__ == "__main__":
    main()
