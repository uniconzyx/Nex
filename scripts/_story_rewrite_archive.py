def eff(s: str) -> int:
    s = re.sub(r"`[^`]+`", "X", s)
    s = re.sub(r"[A-Za-z][A-Za-z0-9_.]*", "X", s)
    return len(s)


def main() -> None:
    doc = json.loads(SRC.read_text(encoding="utf-8"))
    hit = 0
    for subj in doc["subjects"].values():
        for act in subj["acts"]:
            for ch in act["chapters"]:
                if ch["id"] in NEW:
                    ch["line"] = NEW[ch["id"]]
                    hit += 1
    missed = set(NEW) - {
        c["id"] for s in doc["subjects"].values() for a in s["acts"] for c in a["chapters"]
    }
    if missed:
        raise SystemExit(f"这些 id 在文件中不存在：{sorted(missed)}")
    SRC.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    lens = [eff(v) for v in NEW.values()]
    print(f"改写 {hit} 条 · 有效长度 {min(lens)}~{max(lens)} · 平均 {sum(lens)//len(lens)}")


if __name__ == "__main__":
    main()
