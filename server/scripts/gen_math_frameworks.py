def main() -> int:
    m2 = json.loads((FW / "m2.json").read_text(encoding="utf-8"))
    m1 = copy.deepcopy(m2)
    m1["key"] = "m1"
    m1["label"] = "数学（一）"
    m1["score"] = 150
    m1["intro"] = INTRO_M1 + "本文件按专题给出识别特征与固定解法；「考频年份」为历年命题的归纳性标注，不是真题原文。"

    # 前缀 m2- → m1-
    for t in m1["topics"]:
        t["id"] = t["id"].replace("m2-", "m1-")
        for p in t["patterns"]:
            p["id"] = p["id"].replace("m2-", "m1-")

    for extra in EXTRA:
        tid = f"m1-{extra['id']}"
        topic = {
            "id": tid,
            "title": extra["title"],
            "order": len(m1["topics"]) + 1,
            "heat": extra["heat"],
            "seenIn": extra["seenIn"],
            "points": extra["points"],
            "patterns": [{**p, "id": f"{tid}-{p['id']}"} for p in extra["patterns"]],
        }
        m1["topics"].append(topic)

    for i, t in enumerate(m1["topics"], 1):
        t["order"] = i

    (FW / "m1.json").write_text(
        json.dumps(m1, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print("m1 专题", len(m1["topics"]), "题型", sum(len(t["patterns"]) for t in m1["topics"]))
    print("m2 专题", len(m2["topics"]), "题型", sum(len(t["patterns"]) for t in m2["topics"]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
