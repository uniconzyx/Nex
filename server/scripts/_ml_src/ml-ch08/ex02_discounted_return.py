# title: 折扣回报：γ 同时决定「看多远」和「方差多大」
# 有限期 G_H = Σ_{k<H} γ^k r 与无限期 G 的缺口随 H 按 γ^H 指数消失；
# 但 γ→1 时，价值尺度按 1/(1−γ)、蒙特卡洛回报的方差按 σ²/(1−γ²) 双双爆炸。
import numpy as np

rng = np.random.default_rng(11)

print("== 1) 有限期 vs 无限期（每步奖励恒为 1，γ=0.9）==")
G = 0.9
G_inf = 1.0 / (1 - G)
print(f"{'期界H':>6} {'有限期G_H':>10} {'无限期G':>10} {'缺口':>10}")
for H in (1, 2, 5, 10, 20, 50):
    G_H = sum(G ** k for k in range(H))
    print(f"{H:>6} {G_H:>10.4f} {G_inf:>10.4f} {G_inf - G_H:>10.2e}")

print("\n== 2) γ 这个旋钮的三重效应（每步奖励上界 r_max = 1）==")
print(f"{'γ':>7} {'有效视界1/(1−γ)':>16} {'前10步权重占比':>14} {'价值尺度r_max/(1−γ)':>20}")
for g in (0.0, 0.5, 0.9, 0.99, 0.999):
    horizon = 1.0 if g == 0.0 else 1.0 / (1 - g)
    frac10 = 1.0 if g == 0.0 else 1.0 - g ** 10      # Σ_{k<10}γ^k / Σ_{k<∞}γ^k
    scale = 1.0 / (1 - g) if g < 1 else float("inf")
    print(f"{g:>7.3f} {horizon:>16.2f} {frac10:>13.1%} {scale:>20.2f}")

print("\n== 3) 蒙特卡洛回报的方差：Var(G) = σ²/(1−γ²)（r_k ~ N(0,1) i.i.d.）==")
print(f"{'γ':>6} {'理论方差':>10} {'实测方差':>10} {'相对偏差':>9}")
for g in (0.5, 0.9, 0.99):
    n, K = 5000, 2000                 # γ^2000 已可忽略，等价无限期
    acc = np.zeros(n)
    w = 1.0
    for _ in range(K):
        acc += w * rng.normal(0.0, 1.0, n)
        w *= g
    theo = 1.0 / (1 - g ** 2)
    print(f"{g:>6.2f} {theo:>10.2f} {acc.var():>10.2f} {abs(acc.var() - theo) / theo:>9.2%}")

print("\n结论：γ 是同一个旋钮的三面——γ 越大，有效视界 1/(1−γ) 越长、价值尺度越大、")
print("蒙特卡洛估计方差越大（γ=0.99 时方差 50.3，是 γ=0.9 的约 9.5 倍）。")
print("工程含义：想「看得远」不能只调大 γ，必须同步换估计量（TD/动态规划）或压方差；")
print("另外，无限期折扣回报有限的前提正是 γ<1——γ=1 只在有终止态的有限期任务里才良定义。")
