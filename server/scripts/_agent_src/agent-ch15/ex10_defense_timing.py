# title: 15 分钟答辩脚本：时间盒分配、要点覆盖检查与超时砍序
# 纯标准库实现：五段时间盒（合计 15 分钟）、每段「可核对数字」覆盖检查与超时砍序表。


def dw(s):
    return sum(2 if ord(c) > 127 else 1 for c in s)


def pad(s, w):
    return s + " " * max(1, w - dw(s))


# 五段答辩：名称 -> (分钟, 必须覆盖的要点, 可核对数字)
SCRIPT = [
    ("选题与痛点", 2, ["谁的用户(3 人反馈)", "痛点频率与现状代价", "差异化一句话"], "用户数/痛点频率"),
    ("方案与架构", 3, ["架构图一页", "一个关键取舍", "依赖与故障点"], "组件数/延迟预算"),
    ("演示", 5, ["核心任务 2 分钟", "一个失败案例+兜底", "视频兜底待命"], "任务完成数/失败归因"),
    ("数据", 3, ["黄金集三列对比", "帕累托头部变化", "监控四指标+单次成本"], "通过数/成本数字"),
    ("复盘与下一步", 2, ["目标 vs 实际", "两个做错的决定", "重来的排期"], "达成率/下轮排期"),
]

total_min = sum(m for _, m, _, _ in SCRIPT)
print(f"== 1) 时间盒（合计 {total_min} 分钟，每段独立计时） ==")
print("  " + pad("段", 14) + pad("分钟", 6) + pad("累计", 6) + pad("占比", 7) + "必须覆盖")
cum = 0
bar = ""
for name, m, points, num in SCRIPT:
    cum += m
    print("  " + pad(name, 14) + pad(str(m), 6) + pad(str(cum), 6) + pad(f"{m / total_min:.0%}", 7)
          + "、".join(points))
    bar += f"[{name}|{m}分]"
print("  时间轴: " + bar)

print("\n== 2) 要点覆盖检查：每段至少一个「可核对数字」，缺数字 = 没准备 ==")
print("  " + pad("段", 14) + pad("数字口径", 18) + pad("彩排就绪", 8) + "检查问题")
ready = 0
for name, m, points, num in SCRIPT:
    ok = bool(num)
    ready += ok
    print("  " + pad(name, 14) + pad(num, 18) + pad("是" if ok else "否", 8)
          + "这一段的数字，观众能复述吗？")
print(f"  {ready}/{len(SCRIPT)} 段有数字口径 -> {'可上台' if ready == len(SCRIPT) else '补数字再上台'}")

# 反例：复盘段的数字口径空缺（最常见——「做了很多但说不上来」）
weak = [(n, m, p, (num if n != "复盘与下一步" else "")) for n, m, p, num in SCRIPT]
gaps = [n for n, m, p, num in weak if not num]
print(f"\n  反例脚本（复盘段缺数字）: 缺口 = {gaps} -> 报警「复盘与下一步 缺可核对数字」")
print("  常见症状：讲了一堆「学到了很多」，观众复述不出任何一个数——这段等于没讲")

print("\n== 3) 超时砍序（从前往后砍，演示永远最后砍且只砍到核心 60 秒） ==")
CUT_ORDER = [
    ("复盘与下一步", "压到 1 分钟：只讲两个做错的决定"),
    ("方案与架构", "只留架构图 + 一个取舍，细节进问答"),
    ("数据", "只讲三列对比与单次成本两个数"),
    ("演示", "最后手段：跳过失败案例，只演核心任务 60 秒"),
]
print("  " + pad("超出时砍", 14) + "砍法")
for seg, how in CUT_ORDER:
    print("  " + pad(seg, 14) + how)
print("  永不砍：演示的核心任务段（它是全场唯一「证据」）与数据段的三列对比")

print("\n== 4) 必答三问（答不上来 = 选题或数据没准备） ==")
for q, a in [("谁会用？", "3 个真实用户 + 痛点频率（数字）"),
             ("效果如何？", "黄金集通过数 + 三列对比（数字）"),
             ("成本多少？", "单次成本 + burn rate（数字）")]:
    print(f"  {q} -> {a}")
print("  三个问题各配一个数字，是答辩材料的最低配置；功能列表不配数字等于没讲")

print("\n结论：15 分钟答辩是叙事不是功能罗列——时间盒按 2/3/5/3/2 分配，每段配一个可核对数字；")
print("读法：1. 演示段占 1/3 且永远最后才砍：它是唯一「证据」，其余都是「叙述」；2. 失败案例要主动讲，附归因与下一轮排期——比被问出来专业一个量级；3. 超时砍序预先写定（复盘->方案->数据->演示），现场不纠结；4. 本示例为脚本规划工具，真实答辩前按此表彩排两遍并计时。")
