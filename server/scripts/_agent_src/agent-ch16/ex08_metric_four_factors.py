# title: 量化指标四要素打分：同一个 92% 在三种写法下的可信度差多少
# 本地模拟：内置 bullet 组的四要素检查与对比实验，不调用任何外部服务。
# 目的：把「数字≠证据」变成可度量的评分——四要素（基线/口径/归因/对比）缺一个扣一分。


def metric_score(bullet):
    """四要素自检：返回 (得分, 缺失项)。关键词近似只是初筛，最终判断在人。"""
    checks = {
        "基线": ("→" in bullet) or ("从" in bullet and "到" in bullet),
        "口径": any(k in bullet for k in ("条", "样本", "查询", "天", "周", "次", "起", "A/B")),
        "归因": any(k in bullet for k in ("独立", "负责", "重写", "引入", "替换", "定位", "改")),
        "对比": ("→" in bullet) or ("高于" in bullet) or ("低于" in bullet),
    }
    missing = [k for k, ok in checks.items() if not ok]
    return len(checks) - len(missing), missing


BULLETS = [
    # 同一个 92% 的三种写法
    "准确率达到 92%",                                                   # 只有数字
    "准确率从 72% 提升到 92%",                                           # 有基线，没口径/归因/对比
    "独立重写重排模块：1000 条样本上答案准确率 72%→92%，高于开源默认配置 4 个点",  # 四要素齐
    # 另外两条常见残缺点法
    "A/B 同流量两周，接口 P99 从 850ms 降到 210ms，瓶颈定位为同步 OCR 调用",     # 缺对外部参照的对比
    "值班期间处理 3 起检索超时告警，定位为索引未预热，已补预热脚本",              # 无百分比的行为证据
]

print("== 四要素打分（满分 4） ==")
print(f"{'#':<3}{'得分':>4}  {'缺失要素':<20}bullet")
for i, b in enumerate(BULLETS, 1):
    s, missing = metric_score(b)
    print(f"{i:<3}{s:>4}  {('、'.join(missing) or '无'):<20}{b[:38]}")

# 对比实验：同一个 92%，三种写法的分差
s1, _ = metric_score(BULLETS[0])
s2, _ = metric_score(BULLETS[1])
s3, _ = metric_score(BULLETS[2])
print(f"\n== 同一个 92% 的对比实验 ==")
print(f"  「准确率达到 92%」            -> {s1}/4（光秃秃一个数字：无基线、无口径、无归因、无对比）")
print(f"  「准确率从 72% 提升到 92%」    -> {s2}/4（有基线，仍答不上『凭什么归因于你』『怎么测的』）")
print(f"  「独立重写…1000 条…72%→92%…」  -> {s3}/4（四要素齐：可追问三层而不塌）")
assert (s1, s2, s3) == (0, 1, 4), (s1, s2, s3)

# 行为证据的特例：无百分比但可核对
s5, m5 = metric_score(BULLETS[4])
print(f"\n== 特例：无百分比的行为证据 ==")
print(f"  「{BULLETS[4][:24]}…」 -> {s5}/4，缺失 {m5}")
print("  判读：『3 起告警 + 定位原因 + 补脚本』是可核对的行动证据，虽无百分比仍强于 0 分的裸数字；")
print("  简历里允许少量这类 bullet，但带数字的必须占多数——面试官按数字追问的成本最低。")

# 加权口径：面试追问视角下四要素的不同权重（经验判断）
WEIGHTS = {"基线": 1.0, "口径": 1.0, "归因": 1.5, "对比": 0.5}
print("\n== 追问视角加权（归因最难答对，权重最高——经验判断） ==")
for i, b in enumerate(BULLETS, 1):
    s, missing = metric_score(b)
    w = sum(WEIGHTS[m] for m in missing)
    print(f"  第 {i} 条：缺失加权损失 {w:.1f}/3.5（缺 {('、'.join(missing) or '无')}）")

print("\n结论：四要素是数字成为证据的最低条件，同一个 92% 可以得 0 分也可以得 4 分，差别全在写法；")
print("读法：1. 基线回答「从多少到多少」——0→92% 和 90%→92% 是两回事；2. 口径回答「怎么测的」——多少样本、什么判定规则（字段级全等还是字符级）；3. 归因回答「凭什么算你的」——A/B、同流量对照、其余模块未动，主动缩小功劳范围比被拆穿便宜；4. 对比回答「好在哪一档」——高于/低于什么参照；5. 关键词检查只是初筛，「1000 条样本是否独立同分布」这类真问题要人工判断（对应 concept/01 第 2 节）。")
