# title: 兜底率敏感性：毛利转负边界与两个修复杠杆的优先级
# 失效边界实验（示例测算）：扫描人工兜底率与人工单价，定位毛利转负点。

Q = 30000          # 月任务量（示例测算）
C_FIX = 20000.0
TOK = 0.030        # token ¥/任务（示例测算）
GPU = 0.012
VEC = 0.004
P = 3.50           # 市场报价 ¥/任务（示例测算，贴近成本的竞争性定价）
HUMAN = 8.0        # 单次人工全价 ¥（8 分钟 × 时薪 60，示例测算）


def pad(s, w):
    return s + " " * max(1, w - sum(2 if ord(c) > 127 else 1 for c in s))


def margin(fb_rate, human=HUMAN, price=P):
    c = TOK + GPU + VEC + fb_rate * human
    return price - C_FIX / Q - c, c


print(f"== 兜底率扫描（Q={Q:,}/月，报价 ¥{P}/任务，人工 ¥{HUMAN}/次；示例测算） ==")
print(f"{pad('兜底率', 8)}{'单任务成本':>11}{'单任务毛利':>11}{'月毛利':>13}{'状态':>8}")
breakeven = None
for fb in (0.05, 0.10, 0.20, 0.25, 0.30, 0.35, 0.40, 0.50, 0.60):
    m_unit, c = margin(fb)
    m_month = m_unit * Q
    tag = "盈利" if m_month > 0 else "亏损"
    if breakeven is None and m_month <= 0:
        breakeven = fb
    print(f"{pad(f'{fb:.0%}', 8)}{c:>11.3f}{m_unit:>+11.3f}{m_month:>+13,.0f}{tag:>8}")

# 解析解：兜底率临界点 fb* 使月毛利=0
fb_star = (P - C_FIX / Q - TOK - GPU - VEC) / HUMAN
print(f"\n临界兜底率 fb* = {fb_star:.1%}（超过即亏损；此处扫描首负档为 {breakeven:.0%}）")

print("\n== 两个修复杠杆对比（同样服务于兜底率 40% 的现状） ==")
m0, c0 = margin(0.40)
m1, c1 = margin(0.25)            # 杠杆一：提准确率，兜底 40%→25%
m2, _ = margin(0.40, human=6.0)  # 杠杆二：降人工价，¥8→¥6（外包/工具提效）
print(f"提准确率（兜底40%→25%）: 月毛利 {m0*Q:+,.0f} → {m1*Q:+,.0f}（Δ={(m1-m0)*Q:+,.0f}）")
print(f"降人工价（¥8→¥6）     : 月毛利 {m0*Q:+,.0f} → {m2*Q:+,.0f}（Δ={(m2-m0)*Q:+,.0f}）")
print(f"杠杆一比杠杆二多挽回 ¥{((m1-m0)-(m2-m0))*Q:,.0f}/月 —— 质量杠杆优先于价格杠杆")

print("\n结论：兜底率是毛利的第一杀手，临界兜底率 fb*=(报价−固定摊薄−技术成本)/人工单价，超过即亏，")
print("读法：1. 兜底成本=兜底率×人工全价，人工全价=时长×时薪，报价前必须用真实分布估兜底率（POC 的干净数据会系统性低估）；2. 两个修复杠杆不等价：提准确率改变概率、降人工单价改变单价，同幅度下质量杠杆收益更大（0.15×8=1.2 vs 0.40×2=0.8 元/任务）；3. 商务对冲：合同写「兜底率超阈值重新议价」+ 兜底样本回流成测试集；4. 参数为教学假设（示例测算），边界形状比绝对数字重要。")
