# title: 灾难遗忘模拟：新任务涨分与旧任务掉分的权衡
# 用两条可控曲线模拟「继续训练」：新任务按饱和曲线上升，旧任务按衰减曲线下滑；
# 再加入 replay（混入旧数据）看能否把旧能力拉回来。
import numpy as np

steps = np.arange(0, 801, 50)

def curves(n_steps, replay=0.0):
    # replay 的代价：新任务上限略降、收敛略慢（要分容量给旧数据）
    new = (0.92 - 0.10 * replay) * (1 - np.exp(-n_steps / (120.0 * (1 + replay))))
    decay = 0.55 / (1 + 3.5 * replay)                       # replay 越大，遗忘越慢
    old = 0.78 * np.exp(-decay * n_steps / 400.0) + 0.10
    return new, old

print("旧任务初始准确率 0.88（新任务初始 0.0）；replay = 混入旧数据的比例\n")
print(f"{'steps':>6}{'新任务':>8}{'旧任务':>8}{'均值':>8}   |"
      f"{'replay=0.2 新':>14}{'旧':>7}{'均值':>8}")
for s in steps:
    n0, o0 = curves(s, 0.0)
    n1, o1 = curves(s, 0.2)
    print(f"{s:>6}{n0:>8.3f}{o0:>8.3f}{(n0+o0)/2:>8.3f}   |"
          f"{n1:>14.3f}{o1:>7.3f}{(n1+o1)/2:>8.3f}")

n, o = curves(800, 0.0)
n2, o2 = curves(800, 0.2)
print(f"\n纯新任务训 800 步：新 {n:.3f}，旧 {o:.3f}，旧能力掉了 {(0.88-o)/0.88:.0%}")
print(f"混 20% 旧数据：    新 {n2:.3f}，旧 {o2:.3f}，旧能力只掉 {(0.88-o2)/0.88:.0%}")
print(f"代价：新任务从 {n:.3f} 降到 {n2:.3f}，用 {n-n2:.3f} 的新任务分数换 {o2-o:.3f} 的旧任务分数")

print("\n结论：灾难遗忘不是「模型坏了」，是参数更新方向与旧任务的最优方向冲突。")
print("读法：")
print("1. 先把「旧任务」定义清楚并放进留出集，否则掉分了都不知道；")
print("2. replay 5%~20% 通常性价比最高；更高会把新任务压回去；")
print("3. LoRA 只更新低秩增量，本身就能减轻遗忘，但不能替代 replay —— 两者叠加最稳。")
