# title: 引用溯源校验：6 句答案都带引用，仍有 1 句的来源与内容无关
# 用字符二元组 Jaccard 做「答案句 vs 被引片段」的粗对齐，不加载 NLI 模型。
# 它能抓住「引用了不存在的编号」和「编号存在但内容不支持」两类问题，抓不住蕴含关系。
import re

SOURCES = {
    "S1": "7B 模型以 FP16 加载时，权重约占 14 GB，在 4090 的 24 GB 显存上只剩约 9 GB 留给 KV Cache 与激活。",
    "S2": "KV Cache 的显存等于 2 乘以层数乘以 KV 头数乘以头维度乘以字节宽，再乘以序列长度与并发数。",
    "S3": "连续批处理在新请求到达时立即插队，输出长度差异越大，相对静态批处理的吞吐收益越高。",
    "S4": "INT4 量化把权重压到约 3.7 GB，但长上下文下更容易出现重复与胡言。",
    "S5": "多租户场景必须在检索前做权限过滤，缓存键要带租户标识与权限版本。",
}

# (答案句, 引用列表)
ANSWER = [
    ("7B 模型 FP16 权重约 14GB，4090 上剩余显存约 9GB 可给 KV Cache。", ["S1"]),
    ("KV Cache 显存随序列长度和并发数线性增长。", ["S2"]),
    ("连续批处理在输出长度差异大时吞吐收益最高。", ["S3"]),
    ("INT4 量化后权重约 3.7GB，但长文本更容易重复。", ["S4"]),
    ("权限过滤必须前置，缓存键要带租户和权限版本。", ["S5"]),
    ("量化后推理延迟可以降到原来的三分之一。", ["S4"]),          # 引用存在，内容不支持
]


def bigrams(s):
    s = re.sub(r"[\s，。、；：（）()\[\]【】,.;:%]", "", s)
    return {s[i:i + 2] for i in range(len(s) - 1)}


def jaccard(a, b):
    A, B = bigrams(a), bigrams(b)
    return len(A & B) / len(A | B) if A | B else 0.0


print(f"{'#':<3}{'引用':<8}{'最高重合':>9}{'判定':>8}  答案句")
counts = {"支持": 0, "弱支持": 0, "不支持": 0, "无引用": 0}
fake = 0
for i, (sent, cites) in enumerate(ANSWER, 1):
    if not cites:
        verdict, best = "无引用", 0.0
    else:
        best = max(jaccard(sent, SOURCES[c]) for c in cites)
        if best >= 0.38:
            verdict = "支持"
        elif best >= 0.20:
            verdict = "弱支持"
        else:
            verdict = "不支持"
            fake += 1
    counts[verdict] += 1
    print(f"{i:<3}{','.join(cites) or '-':<8}{best:>9.2f}{verdict:>8}  {sent}")

n = len(ANSWER)
cited = n - counts["无引用"]
print(f"\n引用覆盖率 {cited}/{n}，严格支持率 {counts['支持']}/{n}，"
      f"弱支持 {counts['弱支持']}，无支持 {counts['不支持']}，无引用 {counts['无引用']}")
print(f"其中「有引用但内容不支持」{fake} 条——这类是引用溯源真正要抓的：编号看起来齐全，内容却是编的。")
print(f"可核对率（严格支持 + 弱支持）{counts['支持'] + counts['弱支持']}/{n}——这才是能给客户承诺的数字。")

print("\n逐字看重合度低的原因：第 6 句说『延迟降到三分之一』，S4 通篇讲显存与重复，")
print("两句话共享的二元组只有『量化』等少数几个，Jaccard 掉到 0.02。")
print("第 1、4 句与来源的措辞接近，落在严格支持；第 2、3、5 句是改写，只能算弱支持。")

print("\n读法：Jaccard 只能验证『字面重叠』，不能验证『蕴含』。")
print("句子说『A 导致 B』，片段只写了『A 和 B 都出现』，Jaccard 会判支持，但逻辑是错的。")
print("生产做法是两层：先用字面/向量相似度做廉价过滤，再用 NLI 模型或人工抽检做蕴含判定；")
print("线上还要把『引用编号是否存在』作为硬校验——编号不存在直接判为编造，不用看分数。")
print("\n结论：引用溯源的最低验收口径是『每个论断都能定位到片段，且片段可被人工在 30 秒内核对』；")
print("只统计引用覆盖率会得到 6/6 的漂亮数字，而严格可用的只有 2/6、可核对的是 5/6。")
