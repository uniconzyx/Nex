# title: 需求-能力匹配矩阵：先看「谁能做」，再看「差多少」
# 7 条需求 × 4 项能力（0=不支持，1=勉强，2=可用，3=强），加权算覆盖率并定位缺口。
# 用途：在写方案前把「需求承诺」和「技术能力」对齐，避免立项后才发现关键项没人能做。

CAPS = ["LLM 生成", "函数调用", "检索 RAG", "规则引擎"]
REQS = [
    ("R1 多轮政策问答", 0.22, [3, 2, 3, 0]),
    ("R2 查询订单状态", 0.18, [1, 3, 1, 2]),
    ("R3 回答需引用条款", 0.18, [2, 1, 3, 0]),
    ("R4 计算退款金额", 0.14, [1, 1, 0, 3]),
    ("R5 生成工单摘要", 0.10, [3, 1, 1, 0]),
    ("R6 低置信转人工", 0.10, [2, 3, 1, 3]),
    ("R7 批量导出对账", 0.08, [1, 1, 1, 1]),
]

print("评分：0 不支持 / 1 勉强 / 2 可用 / 3 强；需求权重之和 = 1\n")
print(f"{'需求':<18}{'权重':>5}  " + "".join(f"{c:>10}" for c in CAPS) + f"{'覆盖度':>8}  缺口")
total_cov = 0.0
gaps = []
for name, w, scores in REQS:
    best = max(scores)
    cov = w * best / 3
    total_cov += cov
    gap = "是" if best <= 1 else ""
    if gap:
        gaps.append((name, [CAPS[i] for i, v in enumerate(scores) if v == best]))
    print(f"{name:<18}{w:>5.2f}  " + "".join(f"{v:>10}" for v in scores) + f"{cov:>8.3f}  {gap}")

print(f"\n加权覆盖率：{total_cov:.1%}（满分 1.0；低于 80% 不建议按原范围立项）")
print(f"缺口需求：{len(gaps)} 条")
for name, able in gaps:
    print(f"  - {name}：当前最高能力是「{'/'.join(able)}」=1，需要补数据、补规则或改承诺")

print("\n读法：R7 的四项能力都只有 1 分，不是「都能做一点」，而是「没有一个能交付」；")
print("      覆盖率是加权上限，真实交付还要乘上数据可得性与集成成本。")
print("结论：匹配矩阵要在需求评审时公开——它把「我觉得能做」变成「哪一项、差几分、谁来补」。")
