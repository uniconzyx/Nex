# title: 能力矩阵自评到差距排序：把「我不会」拆成可排期的缺口
# 四维（工程/模型/产品/业务）× 5 级行为锚点。自评后按目标岗位加权，算缺口与补齐成本，
# 输出「每小时能补多少缺口分」的排序——这才是 90 天排期的输入。
DIMS = ["工程", "模型", "产品", "业务"]
ANCHOR = {
    "工程": ["只能跑通脚本", "能写模块并自测", "能设计接口与错误处理", "能扛住线上流量与故障", "能定工程规范并带人"],
    "模型": ["知道名词", "会调 API 与改 prompt", "懂 RAG/微调取舍并做评测", "能定位失败原因并改架构", "能判断技术路线与成本"],
    "产品": ["能提需求", "能写用户故事与验收", "能定义指标与失败兜底", "能取舍范围并推动上线", "能判断商业价值"],
    "业务": ["了解行业名词", "能访谈并复述流程", "能算清客户 ROI", "能设计交付与报价", "能建立行业方法论"],
}
SELF = {"工程": 2, "模型": 2, "产品": 1, "业务": 1}
TARGET = {"工程": 4, "模型": 3, "产品": 3, "业务": 2}
WEIGHT = {"工程": 0.30, "模型": 0.30, "产品": 0.20, "业务": 0.20}
# 每提升 1 级需要的有效投入（小时），含项目练习与复盘
HOURS = {"工程": 90, "模型": 70, "产品": 45, "业务": 50}

print("=" * 74)
print("表 1  能力矩阵自评（0-5 级，锚点只取关键句）")
print("=" * 74)
print(f"{'维度':<6}{'自评':>5}{'目标':>5}{'权重':>7}  当前级别的行为锚点")
for d in DIMS:
    print(f"{d:<6}{SELF[d]:>5}{TARGET[d]:>5}{WEIGHT[d]:>7.2f}  L{SELF[d]}: {ANCHOR[d][max(SELF[d]-1,0)]}")

print("\n" + "=" * 74)
print("表 2  加权差距与补齐成本（缺口按级数计，成本按小时计）")
print("=" * 74)
rows = []
for d in DIMS:
    gap = max(TARGET[d] - SELF[d], 0)
    hours = gap * HOURS[d]
    rows.append((WEIGHT[d] * gap, gap, hours, d))
print(f"{'维度':<6}{'缺口(级)':>9}{'加权缺口':>10}{'需投入h':>9}{'每 100h 补分':>14}")
for wg, gap, hours, d in rows:
    eff = (wg / hours * 100) if hours else 0.0
    print(f"{d:<6}{gap:>9}{wg:>10.2f}{hours:>9}{eff:>14.3f}")

total_gap = sum(r[0] for r in rows)
total_hours = sum(r[2] for r in rows)
print(f"\n合计加权缺口 {total_gap:.2f}（满分 1.00），需 {total_hours} 小时；按每周 12h 计约 {total_hours/12:.1f} 周。")

print("\n" + "=" * 74)
print("表 3  补齐顺序：先补「单位时间收益最高」的维度，而不是缺口最大的")
print("=" * 74)
for i, (wg, gap, hours, d) in enumerate(sorted(rows, key=lambda r: -(r[0] / r[2] if r[2] else 0)), 1):
    print(f"{i}. {d}：缺口 {gap} 级 / {hours}h，补完加权缺口 -{wg:.2f}")

print("\n结论：模型维度的缺口通常最大，但产品/业务的单位时间收益更高——")
print("      因为它们的级数少、每级信息密度大，且面试直接考「你怎么定义指标」。")
print("读法：先补「单位小时收益」高的维度建立正反馈，再用项目把工程/模型缺口压实；")
print("      不要按缺口绝对值排序，那会把 90 天全花在啃最难的一维上。")
