# title: 产业链四层毛利模拟：同样的 100 元收入，四种成本结构
# 把「算力 / 模型 / 推理服务 / 应用与工具」放进同一张单位经济表：
# 收入 100 元，拆成可变成本、固定成本，看毛利率；再看利用率与流失率如何把毛利吃成净利。
# 所有数字为教学用的量级假设（经验判断），不是任何公司的财报。
LAYERS = [
    # 名称, 可变成本明细, 固定成本明细
    ("算力层", {"电费": 18, "带宽": 4, "运维": 8}, {"折旧": 42}),
    ("模型层", {"推理算力": 16, "数据与标注": 5}, {"训练摊销": 26, "人力": 14}),
    ("推理服务", {"上游 token": 52, "失败重试": 4}, {"工程运维": 14, "合规": 4}),
    ("应用与工具", {"模型调用": 26, "交付人力": 18}, {"获客": 24, "研发": 14}),
]

print("=" * 66)
print("表 1  单位经济：每 100 元收入的成本去向（毛利 = 收入 - 全部成本）")
print("=" * 66)
print(f"{'层':<10}{'可变':>7}{'固定':>7}{'总成本':>8}{'毛利率':>8}  最大成本项")
rows = []
for name, var, fix in LAYERS:
    v, f = sum(var.values()), sum(fix.values())
    gm = 100 - v - f
    biggest = max({**var, **fix}.items(), key=lambda kv: kv[1])
    rows.append((name, gm))
    print(f"{name:<10}{v:>7}{f:>7}{v + f:>8}{gm:>7}%  {biggest[0]} {biggest[1]}")

# 算力层的固定成本被利用率摊薄：折旧按 70% 规划利用率计入，实际利用率 u 时每 100 元收入摊 42*0.7/u
print("\n" + "=" * 66)
print("表 2  算力层：利用率对净利率的杠杆（固定成本不随收入下降）")
print("=" * 66)
print(f"{'利用率':>7}{'摊薄后固定':>11}{'净利率':>9}")
for u in (0.35, 0.50, 0.70, 0.85, 0.95):
    fixed = 42 * 0.70 / u
    net = 100 - 30 - fixed
    print(f"{u:>7.0%}{fixed:>11.1f}{net:>8.1f}%")

# 应用层：毛利率 18%，获客成本 260 元，月流失率决定 LTV 与回本周期
print("\n" + "=" * 66)
print("表 3  应用层：流失率决定生死（月 ARPU=100，毛利率 18%，CAC=260）")
print("=" * 66)
print(f"{'月流失':>7}{'LTV':>8}{'LTV/CAC':>9}{'回本(月)':>10}  判定")
for churn in (0.02, 0.035, 0.06, 0.09):
    ltv = 18 / churn
    payback = 260 / 18
    verdict = "健康" if ltv / 260 >= 3 else "危险"
    print(f"{churn:>7.1%}{ltv:>8.0f}{ltv / 260:>9.2f}{payback:>10.1f}  {verdict}")

print("\n结论：四层的毛利率都在 18%~39%，但只有算力层是「重资产 + 高确定性」，")
print("      应用层是「轻资产 + 高流失」——毛利率相同，风险结构完全不同。")
print("读法：B 端应用要先用留存率证明 LTV/CAC>3，再谈扩规模；否则每多卖一单都在放大亏损。")
print("     （表中数字是量级假设，用于建立判断，不是行业统计。）")
