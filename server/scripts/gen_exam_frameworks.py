def write(data: dict) -> None:
    if data["key"] in ("e1", "e2"):
        data["topics"].append(listening_topic(data["key"]))
    for i, t in enumerate(data["topics"], 1):
        t["order"] = i
    (FW / f"{data['key']}.json").write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    n = sum(len(t["patterns"]) for t in data["topics"])
    print(f"{data['key']}: {len(data['topics'])} 专题 / {n} 题型")


