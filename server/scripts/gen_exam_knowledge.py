    (KD / f"{exam}-{subject}.json").write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"{exam}-{subject}: {len(topics)} 专题 / {sum(len(t['knowledge']) for t in topics)} 知识点")


